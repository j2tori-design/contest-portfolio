def set_font(run, size, color=INK, bold=False, italic=False):
    f = run.font
    f.size, f.bold, f.italic = Pt(size), bold, italic
    f.color.rgb = color
    f.name = FONT
    rpr = run._r.get_or_add_rPr()
    for tag in ("a:latin", "a:ea", "a:cs"):
        el = rpr.find(qn(tag))
        if el is None:
            el = rpr.makeelement(qn(tag), {})
            rpr.append(el)
        el.set("typeface", FONT)


def text(slide, x, y, w, h, paras, size=16, color=INK, bold=False, align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP,
         space_after=6, name=None):
    """paras: str | list[str | list[(text, opts)]]"""
    tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    if name:
        tb.name = name
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    tf.vertical_anchor = anchor
    if isinstance(paras, str):
        paras = [paras]
    for i, p in enumerate(paras):
        para = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        para.alignment = align
        para.space_after = Pt(space_after)
        runs = p if isinstance(p, list) else [(p, {})]
        for t, o in runs:
            r = para.add_run()
            r.text = t
            set_font(r, o.get("size", size), o.get("color", color), o.get("bold", bold), o.get("italic", False))
    return tb


def bullets(slide, x, y, w, h, items, size=15, color=INK):
    tb = text(slide, x, y, w, h, items, size=size, color=color, space_after=8)
    for para in tb.text_frame.paragraphs:
        ppr = para._p.get_or_add_pPr()
        ppr.set("marL", str(Emu(Inches(0.25))))
        ppr.set("indent", str(-Emu(Inches(0.25))))
        bu = ppr.makeelement(qn("a:buChar"), {"char": "•"})
        ppr.append(bu)
    return tb


def box(slide, x, y, w, h, fill=CARD, shape=MSO_SHAPE.ROUNDED_RECTANGLE, line=None, radius=0.06):
    s = slide.shapes.add_shape(shape, Inches(x), Inches(y), Inches(w), Inches(h))
    s.fill.solid()
    s.fill.fore_color.rgb = fill
    if line is None:
        s.line.fill.background()
    else:
        s.line.color.rgb = line
        s.line.width = Pt(1.25)
    if shape == MSO_SHAPE.ROUNDED_RECTANGLE:
        s.adjustments[0] = radius
    s.shadow.inherit = False
    return s


def badge(slide, x, y, label, d=0.46, fill=ORANGE, size=15):
    s = box(slide, x, y, d, d, fill=fill, shape=MSO_SHAPE.OVAL)
    tf = s.text_frame
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    tf.vertical_anchor = MSO_ANCHOR.MIDDLE
    p = tf.paragraphs[0]
    p.alignment = PP_ALIGN.CENTER
    r = p.add_run()
    r.text = label
    set_font(r, size, WHITE, bold=True)
    return s


def image(slide, name, x, y, w, h, align="center"):
    path = FIG / name
    iw, ih = Image.open(path).size
    scale = min(w / iw, h / ih)
    pw, ph = iw * scale, ih * scale
    px = x + (w - pw) / 2 if align == "center" else x
    pic = slide.shapes.add_picture(str(path), Inches(px), Inches(y), Inches(pw), Inches(ph))
    pic.name = name
    return pic


def new_slide(kicker=None, title=None, dark=False, notes=""):
    s = prs.slides.add_slide(BLANK)
    state["n"] += 1
    if dark:
        s.background.fill.solid()
        s.background.fill.fore_color.rgb = NAVY
    if kicker:
        text(s, 0.6, 0.38, 10, 0.3, kicker, size=12, color=ORANGE, bold=True, name="kicker")
    if title:
        text(s, 0.6, 0.66, 12.1, 1.0, title, size=26, color=WHITE if dark else INK, bold=True, name="title")
    if state["n"] > 1:
        text(s, SW - 1.1, 7.05, 0.5, 0.25, str(state["n"]), size=10, color=ICE if dark else MUTED,
             align=PP_ALIGN.RIGHT, name="page")
    if notes:
        s.notes_slide.notes_text_frame.text = notes
    return s


def stat(slide, x, y, w, h, big, label, sub, color=ORANGE):
    box(slide, x, y, w, h)
    text(slide, x + 0.3, y + 0.25, w - 0.6, 0.9, big, size=44, color=color, bold=True)
    text(slide, x + 0.3, y + 1.2, w - 0.6, 0.45, label, size=16, color=INK, bold=True)
    text(slide, x + 0.3, y + 1.65, w - 0.6, h - 1.8, sub, size=13, color=INK2)


def callout(slide, x, y, w, items):
    """우측 해설 패널: [(big, small)] 또는 [(big, small, color)]"""
    cy = y
    for big, small, *c in items:
        text(slide, x, cy, w, 0.6, big, size=26, color=c[0] if c else ORANGE, bold=True)
        text(slide, x, cy + 0.62, w, 0.8, small, size=14, color=INK2)
        cy += 1.6


