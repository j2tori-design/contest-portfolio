SCOPE_BY_GROUP = {"대형·기관": "large", "제외": "exclude", "의료": "essential"}


def industry_table() -> pd.DataFrame:
    rows = [
        {"MCT_RY_CD": ry, "ind_group": g, "scope": SCOPE_BY_GROUP.get(g, "core")}
        for g, items in INDUSTRY_GROUPS.items() for ry in items
    ]
    df = pd.DataFrame(rows)
    dup = df[df.MCT_RY_CD.duplicated()]
    if len(dup):
        raise ValueError(f"업종이 두 그룹에 중복 지정됨: {dup.MCT_RY_CD.tolist()}")
    return df
